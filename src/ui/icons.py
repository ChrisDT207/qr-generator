def get_icon(name: str, color: str = "#f8fafc", size: int = 24) -> QIcon:
    """Generate a high-DPI QIcon from built-in vector SVG definitions."""
    template = SVG_TEMPLATES.get(name)
    if not template:
        return QIcon()

    svg_content = template.format(color=color)
    byte_array = QByteArray(svg_content.encode("utf-8"))
    renderer = QSvgRenderer(byte_array)

    pixmap = QPixmap(size, size)
    pixmap.fill(Qt.GlobalColor.transparent)

    painter = QPainter(pixmap)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    renderer.render(painter)
    painter.end()

    return QIcon(pixmap)


def get_pixmap(name: str, color: str = "#f8fafc", size: int = 24) -> QPixmap:
    """Generate a QPixmap directly from vector SVG definitions."""
    template = SVG_TEMPLATES.get(name)
    if not template:
        pixmap = QPixmap(size, size)
        pixmap.fill(Qt.GlobalColor.transparent)
        return pixmap

    svg_content = template.format(color=color)
    byte_array = QByteArray(svg_content.encode("utf-8"))
    renderer = QSvgRenderer(byte_array)

    pixmap = QPixmap(size, size)
    pixmap.fill(Qt.GlobalColor.transparent)

    painter = QPainter(pixmap)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    renderer.render(painter)
    painter.end()

    return pixmap
